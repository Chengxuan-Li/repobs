// Generates docs/api.md from packages/contracts (endpoint list + zod schemas as JSON Schema).
//   node --conditions=development scripts/gen-api-docs.ts           write docs/api.md
//   node --conditions=development scripts/gen-api-docs.ts --check   fail if it is out of date
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { z } from 'zod'
import * as contracts from '../packages/contracts/src/index.ts'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = path.join(root, 'docs', 'api.md')

export function renderApiDocs(): string {
  const lines: string[] = [
    '# HTTP API',
    '',
    '<!-- Generated by scripts/gen-api-docs.ts from packages/contracts. Do not edit by hand. -->',
    '',
    `All endpoints live under \`${contracts.API_PREFIX}\` on the loopback address and are private unless marked *public*. ` +
      'Private endpoints need the session cookie from pairing; state-changing ones also need an `Origin` header from the repobs origin and the ' +
      `\`${contracts.CSRF_HEADER}\` header. There are no CORS headers, no file-reading endpoints and no command execution.`,
    '',
    '| Method | Path | Access | Request | Response | Purpose |',
    '| --- | --- | --- | --- | --- | --- |',
  ]
  for (const e of contracts.API_ENDPOINTS) {
    const link = (name?: string) => (name ? `[${name}](#${name.replace(/\[\]$/, '').toLowerCase()})` : '—')
    lines.push(`| ${e.method} | \`${e.path}\` | ${e.auth} | ${link(e.request)} | ${link(e.response)} | ${e.summary} |`)
  }
  lines.push('', '## Schemas', '', 'JSON Schema generated from the shared zod contracts.', '')
  const names = [
    ...new Set(contracts.API_ENDPOINTS.flatMap((e) => [e.request, e.response]).filter((n): n is string => !!n).map((n) => n.replace(/\[\]$/, ''))),
  ].sort()
  for (const name of names) {
    const schema = (contracts as Record<string, unknown>)[name]
    if (!(schema instanceof z.ZodType)) throw new Error(`No zod schema exported for ${name}`)
    lines.push(`### ${name}`, '', '```json', JSON.stringify(z.toJSONSchema(schema, { unrepresentable: 'any' }), null, 2), '```', '')
  }
  return lines.join('\n')
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = renderApiDocs()
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
    if (current !== text) {
      console.error('docs/api.md is out of date. Run: npm run docs:api')
      process.exit(1)
    }
  } else {
    fs.writeFileSync(target, text)
    console.log('Wrote docs/api.md')
  }
}
